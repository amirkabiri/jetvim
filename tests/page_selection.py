#!/usr/bin/env python3
"""Shift-Page/Home/End selection and Select-mode arrow collapse via real PTY."""
import json
import os
from pathlib import Path
import tempfile
import time

ROOT = Path(__file__).resolve().parent.parent
support = {'__file__': str(ROOT / 'tests/autosave.py')}
exec((ROOT / 'tests/autosave.py').read_text().split('\nwith tempfile.TemporaryDirectory', 1)[0], support)
Editor, equal, STATE = support['Editor'], support['equal'], support['STATE']

with tempfile.TemporaryDirectory(prefix='page-selection-', dir=STATE) as directory:
    project = Path(directory)
    (project / 'home').mkdir()
    original = ['0123456789abcdefghij'] * 220
    (project / 'main.lua').write_text('\n'.join(original) + '\n')
    editor = Editor(project, project / 'home/settings.lua', disabled=True, disable_lsp=True)
    def cursor(): return editor.lua('return vim.api.nvim_win_get_cursor(0)')
    def mode(): return editor.lua('return vim.fn.mode()')
    def selection(): return editor.lua('return require("jetvim.edit").selection()')
    def lines(): return editor.lua('return vim.api.nvim_buf_get_lines(0,0,-1,false)')
    def fixture(content=original, row=100, col=5, typing=True):
        editor.raw(b'\x1b[27u')
        editor.lua('vim.bo.modifiable=true; vim.bo.readonly=false; vim.bo.buftype=""; '
                   'vim.api.nvim_buf_set_lines(0,0,-1,false,vim.json.decode(' + json.dumps(json.dumps(content)) + ')); '
                   'vim.bo.modified=false; vim.api.nvim_win_set_cursor(0,{' + str(row) + ',' + str(col) + '}); return true')
        if typing: editor.raw(b'i')
    def key(value):
        editor.lua('return vim.api.nvim_input(' + json.dumps(value) + ')')
        time.sleep(.09)
    try:
        step = editor.lua('return math.max(1,vim.api.nvim_win_get_height(0)-2)')
        variants = [
            ('legacy shifted page', b'\x1b[6;2~', b'\x1b[5;2~'),
            ('Kitty repeat event', b'\x1b[6;2:2~', b'\x1b[5;2:2~'),
        ]
        for label, down, up in variants:
            fixture()
            owner = editor.lua('return vim.api.nvim_get_current_win()')
            editor.raw(down)
            equal(cursor(), [100 + step, 5], label + ' moves one editor page')
            equal(selection(), [99, 5, 99 + step, 5], label + ' keeps initial anchor')
            equal(mode(), 's', label + ' enters typing selection')
            editor.raw(down)
            equal(selection(), [99, 5, 99 + 2 * step, 5], label + ' grows with repeated key')
            editor.raw(up)
            equal(selection(), [99, 5, 99 + step, 5], label + ' reversal shrinks to same anchor')
            editor.raw(up)
            equal(cursor(), [100, 5], label + ' returns to anchor')
            equal(mode(), 'i', label + ' exact reversal collapses to caret')
            equal(editor.lua('return vim.api.nvim_get_current_win()'), owner, label + ' preserves window')
            equal(lines(), original, label + ' only selects, never edits')
            editor.raw(b'X')
            equal(editor.lua('return vim.api.nvim_get_current_line()'), '01234X56789abcdefghij', label + ' empty selection inserts safely')
        fixture(row=2)
        editor.raw(b'\x1b[5;2~')
        equal(cursor(), [1, 5], 'Shift PageUp clamps first line')
        equal(selection(), [0, 5, 1, 5], 'top clamp selection range')
        editor.raw(b'\x1b[5;2~')
        equal(selection(), [0, 5, 1, 5], 'repeated top clamp does not move anchor')
        fixture(row=219)
        editor.raw(b'\x1b[6;2~')
        equal(cursor(), [220, 5], 'Shift PageDown clamps last line')
        equal(selection(), [218, 5, 219, 5], 'bottom clamp selection range')
        fixture(row=1)
        editor.raw(b'\x1b[5;2~')
        equal(mode(), 'i', 'Shift PageUp at top does not select one unwanted character')
        editor.raw(b'X')
        equal(editor.lua('return vim.api.nvim_get_current_line()'), '01234X56789abcdefghij', 'typing after boundary no-op does not replace text')
        fixture([''], row=1, col=0)
        editor.raw(b'\x1b[6;2~')
        equal(cursor(), [1, 0], 'empty file page selection remains valid')
        equal(mode(), 'i', 'empty file keeps typing')
        fixture()
        editor.raw(b'\x1b[6;2~'); editor.raw(b'X')
        equal(editor.lua('return vim.api.nvim_buf_line_count(0)'), 220 - step, 'typing replaces page range across lines')
        equal(cursor(), [100, 6], 'replacement caret follows inserted character')
        equal(editor.lua('return vim.api.nvim_get_current_line()'), '01234X56789abcdefghij', 'page replacement preserves both endpoints')
        content = original.copy(); content[99 + step] = 'x'; content[99 + 2 * step] = 'ab界caféZ'
        fixture(content, col=7)
        editor.raw(b'\x1b[6;2~')
        equal(cursor(), [100 + step, 1], 'short selected target clips column')
        editor.raw(b'\x1b[6;2~')
        equal(cursor(), [100 + 2 * step, len('ab界caf'.encode())], 'selection restores preferred visual column on UTF8 target')
        editor.raw(b'\x1b[5;2~'); editor.raw(b'\x1b[5;2~')
        equal(cursor(), [100, 7], 'selection reversal restores preferred column')
        equal(mode(), 'i', 'UTF8 reversal collapses safely')
        fixture()
        key('<S-PageUp>')
        equal(selection(), [99 - step, 5, 99, 5], 'direct ShiftPageUp uses same movement')
        editor.raw(b'\x1b[6;2~')
        equal(mode(), 'i', 'native reversal after direct mapping collapses')
        for start, end in [(b'\x1b[1;2H', b'\x1b[1;2F'), (b'\x1b[7;2~', b'\x1b[8;2~')]:
            fixture()
            editor.raw(start)
            equal(selection(), [99, 0, 99, 5], 'FnShiftLeft/Home selects to line start')
            fixture()
            editor.raw(end)
            equal(selection(), [99, 5, 99, 20], 'FnShiftRight/End selects to line end')
            editor.raw(b'X')
            equal(editor.lua('return vim.api.nvim_get_current_line()'), '01234X', 'typing replaces Home/End selection')
        # The user's CmdA-at-EOF then Up case; arrow must collapse, not move
        # one row from the selection's active EOF endpoint.
        for arrow, expected in [(b'\x1b[A', [1, 0]), (b'\x1b[D', [1, 0]),
                                (b'\x1b[B', [220, 20]), (b'\x1b[C', [220, 20])]:
            fixture(row=220, col=20)
            editor.raw(b'\x1b[97;9u')
            equal(mode(), 's', 'native CmdA selects file')
            editor.raw(arrow)
            equal(cursor(), expected, 'ordinary arrow collapses CmdA to appropriate endpoint')
            equal(mode(), 'i', 'selection collapse returns to typing')
            equal(selection(), None, 'arrow leaves no selection')
            editor.raw(b'X')
            equal(editor.lua('return vim.api.nvim_buf_line_count(0)'), 220, 'typing after collapse does not replace whole file')
        # Reverse anchor, Unicode byte endpoints, and native ShiftArrow ranges.
        fixture(['ab界caféZ', 'second', 'third'], row=1, col=len('ab界'.encode()))
        key('<S-Right>'); key('<S-Right>')
        before = selection()
        editor.raw(b'\x1b[D')
        equal(cursor(), [before[0] + 1, before[1]], 'Left collapses partial UTF8 selection to start')
        equal(mode(), 'i', 'partial UTF8 selection collapse keeps typing')
        fixture(['ab界caféZ', 'second'], row=1, col=len('ab界'.encode()))
        editor.raw(b'\x1b[1;2C' * 4)
        editor.raw(b'\x1b[C')
        equal(cursor(), [1, len('ab界café'.encode())], 'Right collapse retains a complete UTF8 byte endpoint')
        editor.raw(b'X')
        equal(editor.lua('return vim.api.nvim_get_current_line()'), 'ab界caféXZ', 'typing after UTF8 end collapse inserts without splitting a code point')
        fixture(row=100, col=5)
        editor.raw(b'\x1b[5;2~')
        editor.raw(b'\x1b[B')
        equal(cursor(), [100, 5], 'Down collapses reversed page selection to its end')
        fixture(row=220, col=20)
        editor.raw(b'\x1b[97;9u\x1b[A')
        equal(cursor(), [1, 0], 'same input batch CmdA then Up collapses to first line')
        equal(mode(), 'i', 'same input batch CmdA collapse keeps typing')
        editor.raw(b'X')
        equal(editor.lua('return vim.api.nvim_get_current_line()'), 'X0123456789abcdefghij', 'typing after batched collapse inserts at BOF')
        fixture()
        editor.raw(b'\x1b[6;2~\x1b[A')
        equal(cursor(), [100, 5], 'same input batch ShiftPageDown then Up collapses to anchor')
        equal(mode(), 'i', 'batched page selection collapse keeps typing')
        fixture(['local value = 42'], row=1, col=8)
        editor.raw(b'\x1b[1;3A\x1b[D')
        equal(cursor(), [1, 6], 'batched structural selection then Left collapses identifier start')
        equal(mode(), 'i', 'batched structural selection collapse keeps typing')
        fixture(row=220, col=20)
        editor.raw(b'\x1b[97;9u\x1b[AX')
        equal(cursor(), [1, 1], 'one-packet CmdA Up X inserts at BOF')
        equal(editor.lua('return vim.api.nvim_get_current_line()'), 'X0123456789abcdefghij', 'printable typeahead is not lost after collapse')
        equal(editor.lua('return vim.api.nvim_buf_get_lines(0,-2,-1,false)[1]'), original[-1], 'typeahead never deletes an unrelated EOF character')
        fixture()
        editor.raw(b'\x1b[6;2~X')
        equal(editor.lua('return vim.api.nvim_buf_line_count(0)'), 220 - step, 'one-packet ShiftPageDown X replaces the page selection')
        equal(editor.lua('return vim.api.nvim_get_current_line()'), '01234X56789abcdefghij', 'page selection consumes following text in order')
        fixture()
        editor.raw(b'\x1b[6;2~\x1b[6;2~X')
        equal(editor.lua('return vim.api.nvim_buf_line_count(0)'), 220 - 2 * step, 'repeated page selection plus typing stays ordered in one packet')
        fixture(['local value = 42'], row=1, col=8)
        editor.raw(b'\x1b[1;3AX')
        equal(editor.lua('return vim.api.nvim_get_current_line()'), 'local X = 42', 'structural selection synchronously consumes replacement text')
        fixture()
        bindings = json.loads((ROOT / 'config/keymap.json').read_text())
        all_index = next(i for i, item in enumerate(bindings, 1) if item['id'] == 'select_all')
        editor.raw(f'\x1b[{0xF0000 + all_index}uX')
        equal(lines(), ['X'], 'relay CmdA and printable text replace the file in one packet')
        equal(mode(), 'i', 'synchronous selection replacement keeps typing mode')
        fixture(row=100, col=5)
        editor.raw(b'\x1b[A')
        equal(cursor(), [99, 5], 'plain Up without selection still moves one row')
        fixture(row=100, col=5, typing=False)
        editor.raw(b'\x1b[C')
        equal(cursor(), [100, 6], 'ordinary normal-mode Right still moves one character')
        equal(mode(), 'n', 'ordinary normal-mode arrow never starts typing')
        fixture(row=100, col=5, typing=False)
        key('v'); key('<S-PageDown>')
        equal(mode(), 's', 'page extension can start from Vim visual mode')
        fixture(row=1, col=0, typing=False)
        key('V'); key('<S-PageUp>')
        equal(mode(), 'S', 'linewise selection at boundary remains a full-row selection')
        equal(selection(), [0, 0, 0, 20], 'single-row selection is not confused with an empty caret')
        fixture(row=100, col=5, typing=False)
        key('v'); editor.raw(b'\x1b[A')
        equal(mode(), 'v', 'ordinary arrows preserve explicit Vim Visual mode')
        equal(cursor(), [99, 5], 'Vim Visual arrow still extends instead of collapsing')
        fixture(['first', 'second', 'third'], row=3, col=5, typing=False)
        editor.raw(b'\x1b[97;9u')
        editor.lua('vim.bo.readonly=true; vim.bo.modifiable=false; vim.bo.buftype="nofile"; return true')
        editor.raw(b'\x1b[A')
        equal(cursor(), [1, 0], 'readonly tool selection collapses safely')
        equal(mode(), 'n', 'readonly tool selection never enters insert mode')
        fixture(['editor stays unchanged'], row=1, col=0)
        for shortcut, filetype in [(b'\x1b[102;9u', 'jetvim-search'), (b'\x1b[102;10u', 'jetvim-project-search')]:
            editor.raw(shortcut)
            editor.wait('return vim.bo.filetype == ' + json.dumps(filetype))
            field = editor.lua('return vim.api.nvim_get_current_buf()')
            editor.raw(b'\x1b[5;2~')
            equal(mode(), 'i', 'empty query ShiftPageUp keeps typing')
            editor.raw(b'\x1b[1;2H')
            equal(mode(), 'i', 'empty query ShiftHome keeps typing')
            equal(editor.lua('return vim.api.nvim_get_current_buf()'), field, 'empty query selection does not close popup')
            editor.raw(b'abc')
            editor.raw(b'\x1b[6;2~')
            equal(mode(), 'i', 'single-line query ShiftPageDown remains a caret')
            equal(editor.lua('return vim.api.nvim_get_current_line()'), 'abc', 'query page no-op preserves text')
            editor.lua('vim.api.nvim_buf_set_lines(0,0,-1,false,{""});vim.api.nvim_win_set_cursor(0,{1,0});return true')
            editor.raw(b'\x1b[5;2~X')
            equal(editor.lua('return vim.api.nvim_get_current_line()'), 'X', 'empty query page plus text in one packet preserves the character')
            equal(mode(), 'i', 'empty query synchronous selection remains in typing mode')
            editor.raw(b'\x1b[27u')
        equal(editor.lua('return vim.v.errmsg'), '', 'no selection errors')
        print(f'PASS: {support["checks"]} page/boundary selection and arrow-collapse PTY checks')
    finally:
        editor.close()
